test('chat: a long press opens the message actions (touch)', async ({ page, isMobile }) => {
  test.skip(!isMobile, 'touch only')
  await page.goto('/app/demo/messages')
  await page.getByRole('link', { name: /general/ }).first().click()
  await expect(page.getByRole('heading', { name: 'general' })).toBeVisible()
  await page.waitForTimeout(500)
  const box = page.getByRole('textbox').last()
  await box.fill('Appui long')
  await box.press('Enter')
  const row = page.locator('[data-selectable]').filter({ hasText: 'Appui long' })
  await expect(row).toBeVisible()
  await row.evaluate((el) => el.dispatchEvent(new TouchEvent('touchstart', { bubbles: true, cancelable: true })))
  await page.waitForTimeout(650)
  await expect(page.getByRole('dialog').getByRole('button', { name: /Répondre/ })).toBeVisible()
})
